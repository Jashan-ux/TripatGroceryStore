"""Seed catalogue for Tripat Pansari · MSG Store.

One source of truth for local, staging and (never) production data: the SQL that
``seed.py`` generates is the SQL the database receives, whether it is applied by
Alembic-style tooling, by ``psql``, or through the Supabase connector.

Prices are realistic Mandi Dabwali retail prices in **rupees** here; the seeder
converts to integer paise. Every product has its own stock and specs — nothing
shares a placeholder image, because images are only set when a real one exists
(see the storefront's per-product monogram tile fallback).

Brands that the shop is an authorised dealer for are marked with ``^`` in the
notes column of the brief; nothing here implies a claim beyond stocking the item.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class CategorySeed:
    slug: str
    name: str
    emoji: str
    sort_order: int
    description: str
    children: tuple[tuple[str, str, int], ...] = ()  # (slug, name, sort_order)


@dataclass(frozen=True)
class BrandSeed:
    slug: str
    name: str


@dataclass(frozen=True)
class VariantSeed:
    label: str
    mrp: float
    price: float
    stock: int


@dataclass(frozen=True)
class ProductSeed:
    slug: str
    name: str
    brand: str | None
    category: str
    unit: str
    mrp: float
    price: float
    stock: int
    rating: float
    tags: tuple[str, ...] = ()
    description: str = ""
    variants: tuple[VariantSeed, ...] = field(default_factory=tuple)


