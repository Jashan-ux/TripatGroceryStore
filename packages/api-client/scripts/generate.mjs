#!/usr/bin/env node
/**
 * Regenerate API types from the FastAPI OpenAPI schema.
 *
 * 1. Ask the FastAPI app for its schema (single source of truth).
 * 2. Run openapi-typescript over it.
 *
 * No API type is ever hand-written: if the backend changes, this script (run in
 * CI with a dirty-tree check) fails the build until the frontend is updated.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '../..');
const apiDir = join(repoRoot, 'apps/api');
const schemaFile = join(pkgRoot, 'openapi.json');
const outDir = join(pkgRoot, 'generated');
const outFile = join(outDir, 'schema.d.ts');

function pythonBinary() {
  for (const candidate of ['.venv/bin/python', '.venv/Scripts/python.exe']) {
    const full = join(apiDir, candidate);
    if (existsSync(full)) return full;
  }
  return process.env.PYTHON ?? 'python3';
}

console.log('→ dumping OpenAPI schema from FastAPI');
execFileSync(pythonBinary(), ['-m', 'app.scripts.dump_openapi', schemaFile], {
  cwd: apiDir,
  stdio: 'inherit',
});

console.log('→ generating TypeScript types');
mkdirSync(outDir, { recursive: true });
execFileSync(
  process.platform === 'win32' ? 'npx.cmd' : 'npx',
  ['--no-install', 'openapi-typescript', schemaFile, '--output', outFile],
  { cwd: pkgRoot, stdio: 'inherit' },
);

const banner =
  '// AUTO-GENERATED by packages/api-client/scripts/generate.mjs — do not edit by hand.\n' +
  '// Source: apps/api OpenAPI schema. Regenerate with `npm run api:types`.\n';
writeFileSync(outFile, banner + readFileSync(outFile, 'utf8'));
console.log('✓ types written to', outFile);
